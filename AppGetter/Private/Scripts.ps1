function New-AppGetterMetadataFiles {
    param(
        [pscustomobject]$PackageDetails,
        [string]$VersionDirectory,
        [string]$InstallerFileName,
        [string]$InstallerHash,
        [string]$InstallerInstallCommand,
        [string]$DetectionScript,
        [string]$InstallScript,
        [string]$UninstallScript,
        [string]$IconFilePath,
        [string]$FinalDownloadUrl,
        [pscustomobject]$SwitchDiscoveryResult,
        [pscustomobject]$LicensePattern
    )

    $uninstallCommandLine = Get-IntuneUninstallCommandLine
    $installCommandLine = Get-IntuneInstallCommandLine
    $intuneWinFileName = "$([System.IO.Path]::GetFileNameWithoutExtension($InstallerFileName)).intunewin"

    $installScriptPath = Join-Path $VersionDirectory 'install.ps1'
    $uninstallScriptPath = Join-Path $VersionDirectory 'uninstall.ps1'
    $detectionScriptPath = Join-Path $VersionDirectory 'detection.ps1'
    $readmePath = Join-Path $VersionDirectory 'README.md'
    $appJsonPath = Join-Path $VersionDirectory 'app.json'
    $win32Path = Join-Path $VersionDirectory 'win32LobApp.json'

    $InstallScript | Set-Content -Path $installScriptPath -Encoding UTF8
    $UninstallScript | Set-Content -Path $uninstallScriptPath -Encoding UTF8
    $DetectionScript | Set-Content -Path $detectionScriptPath -Encoding UTF8

    $hasIcon = (Test-Path $IconFilePath)
    $readme = New-AppGetterReadmeMarkdown -PackageDetails $PackageDetails -InstallerFileName $InstallerFileName `
        -InstallerHash $InstallerHash -IntuneWinFileName $intuneWinFileName `
        -InstallerInstallCommand $InstallerInstallCommand -UninstallCommandLine $uninstallCommandLine `
        -FinalDownloadUrl $FinalDownloadUrl -DetectionType 'PowerShell script (registry-based version check)' `
        -HasIcon $hasIcon -SwitchDiscoveryResult $SwitchDiscoveryResult -LicensePattern $LicensePattern
    $readme | Set-Content -Path $readmePath -Encoding UTF8

    $legacyReadme = @"
Package $($PackageDetails.PackageId) $($PackageDetails.Version) from Web Download

Display name: $($PackageDetails.DisplayName)
Version: $($PackageDetails.Version)
Publisher: $($PackageDetails.Publisher)
License: $(if ($LicensePattern) { "$($LicensePattern.DisplayName) [$($LicensePattern.Pattern)]" } else { 'Unknown' })
Website: $($PackageDetails.Homepage)
Download URL: $FinalDownloadUrl

Install command (Intune):
$installCommandLine

Uninstall command (Intune):
$uninstallCommandLine

See README.md for full Intune upload reference.
"@
    $legacyReadme | Set-Content -Path (Join-Path $VersionDirectory 'readme.txt') -Encoding UTF8

    $appJson = @{
        packageIdentifier    = $PackageDetails.PackageId
        displayName          = $PackageDetails.DisplayName
        description          = $PackageDetails.Description
        version              = $PackageDetails.Version
        source               = 3
        publisher            = $PackageDetails.Publisher
        informationUrl       = $PackageDetails.Homepage
        publisherUrl         = if ($PackageDetails.DeveloperUrl) { $PackageDetails.DeveloperUrl } else { $PackageDetails.Homepage }
        supportUrl           = if ($PackageDetails.SupportUrl) { $PackageDetails.SupportUrl } else { $PackageDetails.Homepage }
        installerType        = 7
        installerUrl         = $FinalDownloadUrl
        hash                 = $InstallerHash
        installCommandLine   = $installCommandLine
        uninstallCommandLine = $uninstallCommandLine
        installerFilename    = $InstallerFileName
        installerContext     = 2
        architecture         = 2
    }
    if ($LicensePattern) {
        $appJson.licensing = ConvertTo-AppGetterLicenseMetadata -LicensePattern $LicensePattern
        $licenseJsonPath = Join-Path $VersionDirectory 'license.json'
        $appJson.licensing | ConvertTo-Json -Depth 8 | Set-Content -Path $licenseJsonPath -Encoding UTF8
    }
    if ($SwitchDiscoveryResult) {
        $appJson.switchDiscovery = @{
            installerFamily     = $SwitchDiscoveryResult.InstallerFamily
            primaryType         = $SwitchDiscoveryResult.PrimaryType
            confidenceScore     = $SwitchDiscoveryResult.ConfidenceScore
            verified            = $SwitchDiscoveryResult.Verified
            needsManualReview   = $SwitchDiscoveryResult.NeedsManualReview
            evidenceSummary     = $SwitchDiscoveryResult.EvidenceSummary
            alternativeCommands = $SwitchDiscoveryResult.AlternativeCommands
            recommendedCommand  = $SwitchDiscoveryResult.RecommendedCommand
            installerHash       = $SwitchDiscoveryResult.InstallerHash
            usedCache           = [bool]$SwitchDiscoveryResult.UsedCache
            verificationMethod  = if ($SwitchDiscoveryResult.Verification -and $SwitchDiscoveryResult.Verification.Method) {
                [string]$SwitchDiscoveryResult.Verification.Method
            } else {
                $null
            }
        }

        $silentManifest = [ordered]@{
            engine              = $SwitchDiscoveryResult.InstallerFamily
            primaryType         = $SwitchDiscoveryResult.PrimaryType
            confidenceScore     = $SwitchDiscoveryResult.ConfidenceScore
            command             = $SwitchDiscoveryResult.RecommendedCommand
            verified            = [bool]$SwitchDiscoveryResult.Verified
            needsManualReview   = [bool]$SwitchDiscoveryResult.NeedsManualReview
            evidenceSummary     = @($SwitchDiscoveryResult.EvidenceSummary)
            alternativeCommands = @($SwitchDiscoveryResult.AlternativeCommands)
            installerHash       = $SwitchDiscoveryResult.InstallerHash
            usedCache           = [bool]$SwitchDiscoveryResult.UsedCache
            verificationMethod  = if ($SwitchDiscoveryResult.Verification -and $SwitchDiscoveryResult.Verification.Method) {
                [string]$SwitchDiscoveryResult.Verification.Method
            } else {
                $null
            }
            generatedAt         = (Get-Date).ToUniversalTime().ToString('o')
        }
        $silentManifest | ConvertTo-Json -Depth 8 |
            Set-Content -Path (Join-Path $VersionDirectory 'silent-switches.json') -Encoding UTF8
    }
    $appJson | ConvertTo-Json -Depth 10 | Set-Content -Path $appJsonPath -Encoding UTF8

    $detectionScriptBase64 = [Convert]::ToBase64String([System.Text.Encoding]::UTF8.GetBytes($DetectionScript))
    $iconBase64 = ''
    $iconMimeType = 'image/png'
    if ($hasIcon) {
        $iconBytes = [System.IO.File]::ReadAllBytes($IconFilePath)
        $iconBase64 = [Convert]::ToBase64String($iconBytes)
        $detectedMimeType = Get-ImageMimeType -Bytes $iconBytes
        if ($detectedMimeType) {
            $iconMimeType = $detectedMimeType
        }
    }

    $win32LobAppJson = @{
        '@odata.type'                       = '#microsoft.graph.win32LobApp'
        description                         = $PackageDetails.Description
        developer                           = $PackageDetails.Publisher
        displayName                         = $PackageDetails.DisplayName
        informationUrl                      = $PackageDetails.Homepage
        largeIcon                           = if ($iconBase64) { @{ type = $iconMimeType; value = $iconBase64 } } else { $null }
        notes                               = $(
            $note = "Generated by AppGetter at $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss') [Web|$($PackageDetails.PackageId)]"
            if ($LicensePattern) {
                $note = "$note [License:$($LicensePattern.DisplayName)]"
                if ($LicensePattern.AssignmentGuidance) {
                    $note = "$note $($LicensePattern.AssignmentGuidance)"
                }
            }
            $note
        )
        publisher                           = $PackageDetails.Publisher
        fileName                            = $intuneWinFileName
        allowAvailableUninstall             = $true
        applicableArchitectures               = 'x64'
        detectionRules                      = @(
            @{
                '@odata.type'           = '#microsoft.graph.win32LobAppPowerShellScriptDetection'
                enforceSignatureCheck   = $false
                runAs32Bit              = $false
                scriptContent           = $detectionScriptBase64
            }
        )
        displayVersion                      = $PackageDetails.Version
        installCommandLine                  = $installCommandLine
        installExperience                   = @{
            deviceRestartBehavior = 'basedOnReturnCode'
            runAsAccount          = Get-AppGetterLicenseInstallContext -LicensePattern $LicensePattern
        }
        minimumSupportedOperatingSystem     = @{ v10_2004 = $true }
        minimumSupportedWindowsRelease      = '2004'
        returnCodes                         = @(
            @{ returnCode = 0; type = 'success' }
            @{ returnCode = 1707; type = 'success' }
            @{ returnCode = 3010; type = 'softReboot' }
            @{ returnCode = 1641; type = 'hardReboot' }
            @{ returnCode = 1618; type = 'retry' }
        )
        setupFilePath                       = $InstallerFileName
        uninstallCommandLine                = $uninstallCommandLine
    }

    if (-not $iconBase64) {
        $win32LobAppJson.Remove('largeIcon')
    }

    $win32LobAppJson | ConvertTo-Json -Depth 10 | Set-Content -Path $win32Path -Encoding UTF8

    return [PSCustomObject]@{
        InstallScriptPath   = $installScriptPath
        UninstallScriptPath = $uninstallScriptPath
        DetectionScriptPath = $detectionScriptPath
        ReadmePath          = $readmePath
        AppJsonPath         = $appJsonPath
        Win32LobAppJsonPath = $win32Path
        IntuneWinFileName   = $intuneWinFileName
        InstallCommandLine  = $installCommandLine
        UninstallCommandLine = $uninstallCommandLine
    }
}
