function New-AppGetterInstallScript {
    param(
        [string]$PackageId,
        [string]$DisplayName,
        [string]$Version,
        [string]$InstallCommand,
        [pscustomobject]$LicensePattern
    )

    $licenseHeader = ''
    $licenseApplyBlock = ''
    if ($LicensePattern) {
        $sourceNote = if ($LicensePattern.SourceText) {
            " (ServiceNow: $($LicensePattern.SourceText))"
        } else {
            ''
        }
        $licenseHeader = @"

# Licensing: $($LicensePattern.DisplayName)$sourceNote
# Install context: $($LicensePattern.InstallContext) | Assignment: $($LicensePattern.AssignmentTarget)
"@
        if ($LicensePattern.RequiresLicenseKey) {
            $licenseApplyBlock = @'

    $licenseKey = if (-not [string]::IsNullOrWhiteSpace($env:APPGETTER_LICENSE_KEY)) { $env:APPGETTER_LICENSE_KEY } else { '' }
    if (-not [string]::IsNullOrWhiteSpace($licenseKey)) {
        if ($installCommand -match 'msiexec') {
            $installCommand = "$installCommand PIDKEY=$licenseKey"
        } else {
            $installCommand = "$installCommand /LICENSE=$licenseKey"
        }
        Write-Host 'Applied license key from APPGETTER_LICENSE_KEY.'
    } else {
        Write-Host 'No license key provided (APPGETTER_LICENSE_KEY). Installer may remain unlicensed or prompt.'
    }

'@
        }
    }

    return @"
# Install script for $DisplayName
# Intune Win32 app deployment - generated by AppGetter
$licenseHeader
`$ErrorActionPreference = 'Stop'
`$packageId = '$PackageId'
`$displayName = '$DisplayName'
`$expectedVersion = '$Version'
`$logPath = "`$env:ProgramData\Microsoft\IntuneManagementExtension\Logs\`$packageId-install.log"

Start-Transcript -Path `$logPath -Force
Write-Host "Starting install for `$displayName (`$packageId) version `$expectedVersion"

try {
    `$scriptRoot = Split-Path -Parent `$MyInvocation.MyCommand.Path
    Set-Location -Path `$scriptRoot

    `$installCommand = @'
$InstallCommand
'@
$licenseApplyBlock
    Write-Host "Executing install command: `$installCommand"
    `$process = Start-Process -FilePath 'cmd.exe' -ArgumentList "/c `$installCommand" -Wait -PassThru -NoNewWindow

    switch (`$process.ExitCode) {
        0 { Write-Host 'Install completed successfully.'; Stop-Transcript; exit 0 }
        3010 { Write-Host 'Install completed successfully (reboot required - 3010).'; Stop-Transcript; exit 3010 }
        1641 { Write-Host 'Install completed successfully (hard reboot required - 1641).'; Stop-Transcript; exit 1641 }
        1618 { Write-Host 'Another installation is already in progress (1618).'; Stop-Transcript; exit 1618 }
        default {
            Write-Host "Install failed with exit code `$(`$process.ExitCode)"
            Stop-Transcript
            exit `$process.ExitCode
        }
    }
}
catch {
    Write-Host "Install error: `$_"
    Stop-Transcript
    exit 1
}
"@
}

function New-AppGetterDetectionScript {
    param(
        [string]$PackageId,
        [string]$DisplayName,
        [string]$Version
    )

    $firstWord = ($DisplayName -split '\s+')[0]
    $packageLower = $PackageId.ToLower()

    return @"
# Registry-based detection script for $DisplayName
# Intune Win32 app deployment - generated by AppGetter

`$ErrorActionPreference = 'Continue'
`$packageId = '$PackageId'
`$version = '$Version'
`$displayName = '$DisplayName'
`$logPath = "`$env:ProgramData\Microsoft\IntuneManagementExtension\Logs\`$packageId-detection.log"

Start-Transcript -Path `$logPath -Force
Write-Host "Starting `$packageId `$version detection (registry-based)"

`$registryPaths = @(
    'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*',
    'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*'
)

`$allMatchingVersions = @()

foreach (`$regPath in `$registryPaths) {
    try {
        `$allKeys = Get-ItemProperty `$regPath -ErrorAction SilentlyContinue
        if (-not `$allKeys) { continue }

        `$searchTerms = @('*$DisplayName*', '*$firstWord*', '*$packageLower*')
        `$uninstallKeys = `$allKeys | Where-Object {
            `$key = `$_
            foreach (`$term in `$searchTerms) {
                if ((`$key.DisplayName -and `$key.DisplayName -like `$term) -or (`$key.PSChildName -and `$key.PSChildName -like `$term)) {
                    return `$true
                }
            }
            return `$false
        }

        foreach (`$key in `$uninstallKeys) {
            Write-Host "Found registry key: `$(`$key.PSChildName) | DisplayName: `$(`$key.DisplayName) | DisplayVersion: `$(`$key.DisplayVersion)"

            if (`$key.DisplayName -like '*$DisplayName*' -and `$key.DisplayVersion) {
                `$allMatchingVersions += @{
                    DisplayName = `$key.DisplayName
                    DisplayVersion = `$key.DisplayVersion
                }
            }
        }
    }
    catch {
        Write-Host "Error checking registry path `$regPath : `$_"
    }
}

if (`$allMatchingVersions.Count -eq 0) {
    Write-Host "`$packageId not detected in registry, exiting with code 1"
    Stop-Transcript
    exit 1
}

`$installedVersion = if (`$allMatchingVersions.Count -eq 1) {
    `$allMatchingVersions[0].DisplayVersion
} else {
    (`$allMatchingVersions | Sort-Object { try { [version]`$_.DisplayVersion } catch { [version]'0.0.0' } } -Descending | Select-Object -First 1).DisplayVersion
}

Write-Host "Detected version: `$installedVersion"

if ([string]::IsNullOrWhiteSpace(`$version) -or `$version -eq 'latest') {
    Stop-Transcript
    exit 0
}

try {
    if ([version]`$installedVersion -ge [version]`$version) {
        Write-Host "`$packageId is installed with version `$installedVersion (>= expected `$version)"
        Stop-Transcript
        exit 0
    }
    Write-Host "`$packageId installed version `$installedVersion is lower than expected `$version"
    Stop-Transcript
    exit 1
}
catch {
    if (`$installedVersion -ge `$version) {
        Stop-Transcript
        exit 0
    }
    Stop-Transcript
    exit 1
}
"@
}

function New-AppGetterUninstallScript {
    param(
        [string]$PackageId,
        [string]$DisplayName
    )

    return @"
# Uninstall script for $DisplayName
# Intune Win32 app deployment - generated by AppGetter

`$ErrorActionPreference = 'Stop'
`$packageId = '$PackageId'
`$displayName = '$DisplayName'
`$logPath = "`$env:ProgramData\Microsoft\IntuneManagementExtension\Logs\`$packageId-uninstall.log"

Start-Transcript -Path `$logPath -Force
Write-Host "Starting uninstall for `$displayName (`$packageId)"

`$registryPaths = @(
    'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall\*',
    'HKLM:\SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*'
)

`$uninstallString = `$null
`$quietUninstallString = `$null

foreach (`$regPath in `$registryPaths) {
    try {
        `$uninstallKeys = Get-ItemProperty `$regPath -ErrorAction SilentlyContinue | Where-Object {
            `$_.DisplayName -like '*$DisplayName*' -or
            `$_.PSChildName -like '*$($PackageId.ToLower())*' -or
            `$_.PSChildName -like '*$PackageId*'
        }

        foreach (`$key in `$uninstallKeys) {
            if (`$key.DisplayName -like '*$DisplayName*' -or `$key.DisplayName -eq `$displayName) {
                `$uninstallString = `$key.UninstallString
                `$quietUninstallString = `$key.QuietUninstallString
                Write-Host "Found uninstall string: `$uninstallString"
                break
            }
        }
        if (`$uninstallString) { break }
    }
    catch {
        Write-Host "Error checking registry path `$regPath : `$_"
    }
}

if (-not `$uninstallString) {
    Write-Host 'Uninstall string not found in registry.'
    Stop-Transcript
    exit 1
}

`$uninstallCmd = if (`$quietUninstallString) { `$quietUninstallString } else { `$uninstallString }
if (`$uninstallCmd -notmatch '/S' -and `$uninstallCmd -match '\.exe') {
    `$uninstallCmd = `$uninstallCmd -replace '"([^"]+\.exe)"', '"`$1" /S'
    Write-Host 'Added /S flag for silent uninstall'
}

Write-Host "Executing uninstall command: `$uninstallCmd"

try {
    `$process = Start-Process -FilePath 'cmd.exe' -ArgumentList "/c `$uninstallCmd" -Wait -PassThru -NoNewWindow
    if (`$process.ExitCode -eq 0 -or `$process.ExitCode -eq 3010) {
        Write-Host 'Uninstall completed successfully.'
        Stop-Transcript
        exit 0
    }
    Write-Host "Uninstall returned exit code: `$(`$process.ExitCode)"
    Stop-Transcript
    exit `$process.ExitCode
}
catch {
    Write-Host "Uninstall error: `$_"
    Stop-Transcript
    exit 1
}
"@
}

function New-AppGetterReadmeMarkdown {
    param(
        [pscustomobject]$PackageDetails,
        [string]$InstallerFileName,
        [string]$InstallerHash,
        [string]$IntuneWinFileName,
        [string]$InstallerInstallCommand,
        [string]$UninstallCommandLine,
        [string]$FinalDownloadUrl,
        [string]$DetectionType,
        [bool]$HasIcon,
        [pscustomobject]$SwitchDiscoveryResult,
        [pscustomobject]$LicensePattern
    )

    $generatedAt = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
    $installCommandLine = Get-IntuneInstallCommandLine

    $switchDiscoverySection = ''
    if ($SwitchDiscoveryResult) {
        $verifiedLabel = if ($SwitchDiscoveryResult.Verified) { 'Yes' } else { 'No (static discovery only)' }
        $reviewLabel = if ($SwitchDiscoveryResult.NeedsManualReview) { 'Yes' } else { 'No' }
        $evidenceLines = ($SwitchDiscoveryResult.EvidenceSummary | ForEach-Object { "- $_" }) -join "`n"
        $alternativeLines = if ($SwitchDiscoveryResult.AlternativeCommands.Count -gt 0) {
            ($SwitchDiscoveryResult.AlternativeCommands | ForEach-Object { "- ``$_``" }) -join "`n"
        } else {
            '- None'
        }

        $switchDiscoverySection = @"

## Silent Install Switch Discovery

| Field | Value |
|---|---|
| **Installer family** | $($SwitchDiscoveryResult.InstallerFamily) |
| **Primary type** | $($SwitchDiscoveryResult.PrimaryType) |
| **Confidence score** | $($SwitchDiscoveryResult.ConfidenceScore) / 100 |
| **Runtime verified** | $verifiedLabel |
| **Manual review recommended** | $reviewLabel |

**Evidence:**

$evidenceLines

**Alternative commands considered:**

$alternativeLines

"@
    }

    $licenseSection = ''
    $installBehavior = 'System'
    $licenseTableRow = 'Not specified'
    if ($LicensePattern) {
        $installBehavior = if ($LicensePattern.InstallContext -eq 'user') { 'User' } else { 'System' }
        $licenseTableRow = "$($LicensePattern.DisplayName) ($($LicensePattern.InstallContext) context)"
        $sourceLabel = if ($LicensePattern.SourceText) { $LicensePattern.SourceText } else { '(not provided — inferred or unknown)' }
        $reviewLabel = if ($LicensePattern.NeedsManualReview) { 'Yes' } else { 'No' }
        $keyLabel = if ($LicensePattern.RequiresLicenseKey) { 'Yes (set APPGETTER_LICENSE_KEY or edit install.ps1)' } else { 'No' }
        $licenseEvidenceLines = if ($LicensePattern.EvidenceSummary -and $LicensePattern.EvidenceSummary.Count -gt 0) {
            ($LicensePattern.EvidenceSummary | ForEach-Object { "- $_" }) -join "`n"
        } else {
            '- None'
        }

        $licenseSection = @"

## Licensing

Identified from the ServiceNow license field (or application metadata) and applied to this package.

| Field | Value |
|---|---|
| **ServiceNow license info** | $sourceLabel |
| **Identified pattern** | $($LicensePattern.DisplayName) (``$($LicensePattern.Pattern)``) |
| **Family** | $($LicensePattern.Family) |
| **Metric** | $($LicensePattern.Metric) |
| **Install context** | $($LicensePattern.InstallContext) |
| **Assignment target** | $($LicensePattern.AssignmentTarget) |
| **License key required** | $keyLabel |
| **Confidence** | $($LicensePattern.ConfidenceScore) / 100 |
| **Manual review recommended** | $reviewLabel |

**Evidence:**

$licenseEvidenceLines

**Assignment guidance:** $($LicensePattern.AssignmentGuidance)

**Install guidance:** $($LicensePattern.InstallGuidance)

"@
    }

    return @"
# $($PackageDetails.DisplayName) — Intune Win32 Package

Generated by **AppGetter** on $generatedAt.

## Application Description

$($PackageDetails.Description)

## Intune Portal Upload Reference

Use this section when creating or reviewing the Win32 app in the Microsoft Intune admin center.

| Intune field | Value |
|---|---|
| **Name / Display name** | $($PackageDetails.DisplayName) |
| **Description** | $($PackageDetails.Description) |
| **Publisher** | $($PackageDetails.Publisher) |
| **Developer** | $($PackageDetails.Developer) |
| **App version / Display version** | $($PackageDetails.Version) |
| **Package ID** | ``$($PackageDetails.PackageId)`` |
| **Information URL** | $($PackageDetails.Homepage) |
| **Download URL** | $FinalDownloadUrl |
| **Install command** | ``$installCommandLine`` |
| **Uninstall command** | ``$UninstallCommandLine`` |
| **Setup file / Installer file name** | ``$InstallerFileName`` |
| **IntuneWin package file** | ``$IntuneWinFileName`` |
| **Installer SHA-256** | ``$InstallerHash`` |
| **Detection method** | $DetectionType |
| **Applicable architecture** | x64 |
| **Minimum Windows release** | Windows 10 2004 (20H1) |
| **Install behavior** | $installBehavior |
| **Device restart behavior** | Based on return code |
| **Allow available uninstall** | Yes |
| **Return codes** | 0, 1707 (success); 3010, 1641 (reboot); 1618 (retry) |
| **Icon included** | $(if ($HasIcon) { 'Yes (`icon.png`)' } else { 'No' }) |
| **Notes** | Generated by AppGetter [Web\|$($PackageDetails.PackageId)] |
| **License pattern** | $licenseTableRow |

$switchDiscoverySection
$licenseSection
## Package Contents

| File | Purpose |
|---|---|
| ``install.ps1`` | Silent install wrapper with Intune logging and return codes |
| ``uninstall.ps1`` | Registry-based uninstall with silent flags |
| ``detection.ps1`` | Registry-based version detection |
| ``app.json`` | AppGetter metadata export |
| ``license.json`` | Identified ServiceNow licensing pattern and applied packaging rules |
| ``win32LobApp.json`` | Microsoft Graph ``win32LobApp`` definition |
